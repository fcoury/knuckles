import cv2, json
from pathlib import Path
from shapely.geometry import Polygon, LineString
from shapely.ops import split, unary_union

root = Path(__file__).resolve().parents[1]
im = cv2.imread(str(root / "artwork/knuckles/concept.png"), cv2.IMREAD_GRAYSCALE)
_, mask = cv2.threshold(im, 110, 255, cv2.THRESH_BINARY_INV)
contours, hierarchy = cv2.findContours(mask, cv2.RETR_CCOMP, cv2.CHAIN_APPROX_SIMPLE)
polys = []
for i, c in enumerate(contours):
    if hierarchy[0][i][3] != -1 or cv2.contourArea(c) < 30:
        continue
    holes = [
        contours[j][:, 0, :]
        for j in range(len(contours))
        if hierarchy[0][j][3] == i and cv2.contourArea(contours[j]) > 30
    ]
    p = Polygon(c[:, 0, :], holes).buffer(0)
    polys.append(p)
art = unary_union(polys)
# The whitespace separates the emblem and wordmark in the source.
word = unary_union([p for p in polys if p.centroid.y > 750])


def simple_parts(p):
    if p.geom_type != "Polygon":
        for child in p.geoms:
            yield from simple_parts(child)
    elif p.interiors:
        hole = Polygon(p.interiors[0])
        y = hole.representative_point().y
        line = LineString([(p.bounds[0] - 1, y), (p.bounds[2] + 1, y)])
        for child in split(p, line).geoms:
            yield from simple_parts(child)
    else:
        yield p


def points(g, width):
    from shapely.affinity import translate, scale

    x0, y0, x1, y1 = g.bounds
    g = translate(g, -(x0 + x1) / 2, -(y0 + y1) / 2)
    g = scale(g, xfact=width / (x1 - x0), yfact=width / (x1 - x0), origin=(0, 0))
    # Remove sub-print-size islands and pinhole highlights; round narrow spikes.
    g = g.simplify(0.012, preserve_topology=True).buffer(-0.065).buffer(0.065)
    g = g.buffer(0.045).buffer(-0.045).simplify(0.008, preserve_topology=True)
    cleaned = []
    for p in g.geoms if g.geom_type == "MultiPolygon" else [g]:
        if p.area < 0.035:
            continue
        cleaned.append(
            Polygon(p.exterior, [h for h in p.interiors if Polygon(h).area >= 0.035])
        )
    g = unary_union(cleaned)
    return [
        [[round(x, 4), round(y, 4)] for x, y in p.exterior.coords[:-1]]
        for p in simple_parts(g)
    ]


assets = {
    "badge": {"width": 12.5, "polygons": points(art, 12.5)},
    "wordmark": {"width": 22, "polygons": points(word, 22)},
}

# Twin slanted strokes frame the revision below the large wordmark.
for x in (-8, -6, 4.5, 6.5):
    assets["wordmark"]["polygons"].append(
        [[x, 2.5], [x + 1.5, 2.5], [x + 1.15, 3.05], [x - 0.35, 3.05]]
    )
for name, a in assets.items():
    coords = [v for p in a["polygons"] for v in p]
    x0 = min(x for x, y in coords)
    y0 = min(y for x, y in coords)
    x1 = max(x for x, y in coords)
    y1 = max(y for x, y in coords)
    svg = f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{x0 - 0.3} {y0 - 0.3} {x1 - x0 + 0.6} {y1 - y0 + 0.6}">\n'
    svg += (
        "\n".join(
            '<polygon points="' + " ".join(f"{x},{y}" for x, y in p) + '"/>'
            for p in a["polygons"]
        )
        + "\n</svg>\n"
    )
    (root / f"artwork/knuckles/{name}.svg").write_text(svg)
print({n: len(a["polygons"]) for n, a in assets.items()})

# Ergogen loads footprints in an isolated scope, so embed the polygons.
footprint = (
    "// Generated by scripts/build-knuckles-artwork.py. Coordinates are in mm.\nconst artwork = "
    + json.dumps(assets, separators=(",", ":"))
    + ";\n"
)
footprint += r"""
module.exports = {
  params: {designator: 'ART', variant: 'badge', reversible: true},
  body: p => {
    const art = artwork[p.variant];
    if (!art) throw new Error(`Unknown Knuckles artwork: ${p.variant}`);
    const polygons = side => art.polygons.map(poly => {
      const pts = poly.map(([x,y]) => `(xy ${(side === 'B' ? -x : x).toFixed(4)} ${y.toFixed(4)})`).join(' ');
      return `(fp_poly (pts ${pts}) (stroke (width 0) (type solid)) (fill solid) (layer "${side}.SilkS"))`;
    }).join('\n');
    return `(footprint "knuckles_artwork_${p.variant}" (layer "F.Cu") ${p.at}
      (attr board_only exclude_from_pos_files exclude_from_bom)
      (property "Reference" "${p.ref}" (at 0 0 ${p.r}) (layer "F.Fab") hide
        (effects (font (size 1 1) (thickness 0.15))))
      ${polygons('F')} ${p.reversible ? polygons('B') : ''})`;
  }
};
"""
(root / "ergogen/footprints/knuckles_artwork.js").write_text(footprint)
